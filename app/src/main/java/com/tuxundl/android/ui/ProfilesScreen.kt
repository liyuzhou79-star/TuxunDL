/**
 * State holder for the Compose profiles screen.
 *
 * Written by ProfilesActivity (from withProfile, exactly like the old
 * ProfilesDesign setters did) and read by [ProfilesScreen].
 */
class ProfilesUiState {
    var profiles by mutableStateOf<List<Profile>>(emptyList())
    var updatable by mutableStateOf(false)
    var allUpdating by mutableStateOf(false)

    /** Refreshed once a minute by the activity so elapsed labels stay fresh. */
    var now by mutableStateOf(System.currentTimeMillis())

    /** Profile whose bottom-sheet menu is open, if any. */
    var menuProfile by mutableStateOf<Profile?>(null)

    /** QR code dialog content; bitmap generated by the activity. */
    var qrProfile by mutableStateOf<Profile?>(null)
    var qrBitmap by mutableStateOf<Bitmap?>(null)

    val snackbarHostState = SnackbarHostState()
}

@OptIn(ExperimentalMaterial3Api::class, androidx.compose.foundation.ExperimentalFoundationApi::class)
@Composable
fun ProfilesScreen(
    state: ProfilesUiState,
    onRequest: (ProfilesDesign.Request) -> Unit,
    onBack: () -> Unit,
) {
    Scaffold(
        snackbarHost = { SnackbarHost(state.snackbarHostState) },
        topBar = {
            TopAppBar(
                title = { Text(text = stringResource(DesignR.string.profiles)) },
                navigationIcon = {
                    IconButton(onClick = onBack) {
                        Icon(
                            painter = painterResource(DesignR.drawable.ic_baseline_arrow_back),
                            contentDescription = null,
                        )
                    }
                },
                actions = {
                    if (state.updatable) {
                        if (state.allUpdating) {
                            CircularProgressIndicator(
                                modifier = Modifier
                                    .padding(horizontal = 12.dp)
                                    .size(24.dp),
                            )
                        } else {
                            IconButton(
                                onClick = {
                                    state.allUpdating = true
                                    onRequest(ProfilesDesign.Request.UpdateAll)
                                },
                            ) {
                                Icon(
                                    painter = painterResource(DesignR.drawable.ic_baseline_sync),
                                    contentDescription = null,
                                )
                            }
                        }
                    }
                },
            )
        },
        floatingActionButton = {
            FloatingActionButton(onClick = { onRequest(ProfilesDesign.Request.Create) }) {
                Icon(
                    painter = painterResource(DesignR.drawable.ic_baseline_add),
                    contentDescription = null,
                )
            }
        },
    ) { padding ->
        LazyColumn(
            modifier = Modifier
                .fillMaxSize()
                .padding(padding)
                .padding(horizontal = 16.dp, vertical = 12.dp),
            verticalArrangement = Arrangement.spacedBy(12.dp),
        ) {
            items(state.profiles, key = { it.uuid }) { profile ->
                ProfileCard(
                    modifier = Modifier.animateItem(),
                    profile = profile,
                    now = state.now,
                    onClick = { onRequest(ProfilesDesign.Request.Active(profile)) },
                    onMenu = { state.menuProfile = profile },
                )
            }
        }
    }

    val menuProfile = state.menuProfile
    if (menuProfile != null) {
        ProfileMenuSheet(
            profile = menuProfile,
            onDismiss = { state.menuProfile = null },
            onRequest = { request ->
                state.menuProfile = null
                onRequest(request)
            },
        )
    }

    val qrProfile = state.qrProfile
    val qrBitmap = state.qrBitmap
    if (qrProfile != null && qrBitmap != null) {
        AlertDialog(
            onDismissRequest = { state.qrProfile = null },
            title = { Text(text = stringResource(DesignR.string.share_qr_code)) },
            text = {
                Image(
                    bitmap = qrBitmap.asImageBitmap(),
                    contentDescription = null,
                    modifier = Modifier.fillMaxWidth(),
                )
            },
            confirmButton = {
                TextButton(onClick = { state.qrProfile = null }) {
                    Text(text = stringResource(DesignR.string.close))
                }
            },
        )
    }
}

@OptIn(ExperimentalMaterial3Api::class)
@Composable
private fun ProfileCard(
    profile: Profile,
    now: Long,
    onClick: () -> Unit,
    onMenu: () -> Unit,
    modifier: Modifier = Modifier,
) {
    val context = LocalContext.current

    TuxunCard(
        onClick = onClick,
        modifier = modifier.fillMaxWidth(),
    ) {
        Row(
            modifier = Modifier
                .fillMaxWidth()
                .padding(start = 8.dp, end = 4.dp, top = 12.dp, bottom = 12.dp),
            verticalAlignment = Alignment.CenterVertically,
        ) {
            RadioButton(selected = profile.active, onClick = onClick)
            Column(modifier = Modifier.weight(1f)) {
                Text(
                    text = profile.name,
                    style = MaterialTheme.typography.titleMedium,
                )
                Text(
                    text = if (profile.pending) {
                        stringResource(
                            DesignR.string.format_type_unsaved,
                            profile.type.profileTypeString(context),
                        )
                    } else {
                        profile.type.profileTypeString(context)
                    },
                    style = MaterialTheme.typography.bodyMedium,
                    color = MaterialTheme.colorScheme.onSurfaceVariant,
                )
                if (profile.total > 1) {
                    Spacer(modifier = Modifier.height(6.dp))
                    val used = profile.download + profile.upload
                    Row {
                        Text(
                            text = "${used.toBytesString()} / ${profile.total.toBytesString()}",
                            style = MaterialTheme.typography.bodySmall,
                        )
                        if (profile.expire > 0) {
                            Spacer(modifier = Modifier.width(12.dp))
                            Text(
                                text = profile.expire.toDateStr(),
                                style = MaterialTheme.typography.bodySmall,
                            )
                        }
                    }
                    Spacer(modifier = Modifier.height(4.dp))
                    LinearProgressIndicator(
                        progress = {
                            (used.toFloat() / profile.total.toFloat()).coerceIn(0f, 1f)
                        },
                        modifier = Modifier.fillMaxWidth(),
                    )
                }
                Spacer(modifier = Modifier.height(4.dp))
                Text(
                    text = (now - profile.updatedAt).elapsedIntervalString(context),
                    style = MaterialTheme.typography.bodySmall,
                    color = MaterialTheme.colorScheme.onSurfaceVariant,
                )
            }
            IconButton(onClick = onMenu) {
                Icon(
                    painter = painterResource(DesignR.drawable.ic_baseline_more_vert),
                    contentDescription = null,
                )
            }
        }
    }
}

@OptIn(ExperimentalMaterial3Api::class)
@Composable
private fun ProfileMenuSheet(
    profile: Profile,
    onDismiss: () -> Unit,
    onRequest: (ProfilesDesign.Request) -> Unit,
) {
    ModalBottomSheet(onDismissRequest = onDismiss) {
        Column(modifier = Modifier.padding(bottom = 24.dp)) {
            if (profile.imported && profile.type != Profile.Type.File) {
                MenuItem(
                    text = stringResource(DesignR.string.update),
                    onClick = { onRequest(ProfilesDesign.Request.Update(profile)) },
                )
            }
            MenuItem(
                text = stringResource(DesignR.string.edit),
                onClick = { onRequest(ProfilesDesign.Request.Edit(profile)) },
            )
            if (profile.imported) {
                MenuItem(
                    text = stringResource(DesignR.string.duplicate),
                    onClick = { onRequest(ProfilesDesign.Request.Duplicate(profile)) },
                )
            }
            if (profile.imported && profile.type == Profile.Type.Url && profile.source.isNotEmpty()) {
                MenuItem(
                    text = stringResource(DesignR.string.share_qr_code),
                    onClick = { onRequest(ProfilesDesign.Request.ShareQrCode(profile)) },
                )
            }
            MenuItem(
                text = stringResource(DesignR.string.delete),
                onClick = { onRequest(ProfilesDesign.Request.Delete(profile)) },
            )
        }
    }
}

@Composable
private fun MenuItem(
    text: String,
    onClick: () -> Unit,
) {
    TextButton(
        onClick = onClick,
        modifier = Modifier
            .fillMaxWidth()
            .padding(horizontal = 8.dp),
    ) {
        Row(
            modifier = Modifier.fillMaxWidth(),
            horizontalArrangement = Arrangement.Start,
        ) {
            Text(text = text, style = MaterialTheme.typography.bodyLarge)
        }
    }
}
